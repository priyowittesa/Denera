/**
 * One-off generator for the Portfolio map.
 * Reads Natural Earth 1:50m country shapes (public domain, via world-atlas),
 * projects Indonesia and its neighbours with Mercator, and writes plain SVG paths
 * to src/data/indonesiaMap.ts so the app needs no map library at runtime.
 *
 * Run: node scripts/build-map.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { geoMercator, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)))
const countries = feature(topo, topo.objects.countries).features

const INDONESIA = '360'
const NEIGHBOURS = ['458', '096', '626', '598', '608', '702', '036'] // Malaysia, Brunei, Timor-Leste, PNG, Philippines, Singapore, Australia

// Frame: 94.5E to 141.5E, 11.2S to 6.6N, with a little sea around the edges.
const frame = {
  type: 'Feature',
  geometry: { type: 'MultiPoint', coordinates: [[94.5, -11.2], [141.5, 6.6]] },
}
const W = 800
const projection = geoMercator().fitWidth(W, frame)
const [[, y0], [, y1]] = geoPath(projection).bounds(frame)
const H = Math.round(y1 - y0)
projection.translate([projection.translate()[0], projection.translate()[1] - y0]).clipExtent([[0, 0], [W, H]])
const path = geoPath(projection).digits(1)

const pick = (id) => countries.find((c) => c.id === id)
const indonesia = path(pick(INDONESIA))
const neighbours = NEIGHBOURS.map((id) => pick(id)).filter(Boolean).map((f) => path(f)).filter(Boolean)

const [tx, ty] = projection.translate()
const k = projection.scale()

const out = `/**
 * Generated by scripts/build-map.mjs from Natural Earth 1:50m (public domain).
 * Do not edit by hand. Mercator projection, ${W} x ${H}.
 */
export const MAP_W = ${W}
export const MAP_H = ${H}

/** Project longitude and latitude (degrees) to map coordinates. */
export function project(lon: number, lat: number): [number, number] {
  const l = (lon * Math.PI) / 180
  const p = (lat * Math.PI) / 180
  return [${k.toFixed(4)} * l + ${tx.toFixed(4)}, -${k.toFixed(4)} * Math.log(Math.tan(Math.PI / 4 + p / 2)) + ${ty.toFixed(4)}]
}

export const INDONESIA_PATH = ${JSON.stringify(indonesia)}

export const NEIGHBOUR_PATHS: string[] = ${JSON.stringify(neighbours, null, 0)}
`
writeFileSync(new URL('../src/data/indonesiaMap.ts', import.meta.url), out)
console.log(`map ${W}x${H}, indonesia ${indonesia.length} chars, neighbours ${neighbours.length}, file ${(out.length / 1024).toFixed(0)} KB`)
